// Shopping Cart Utility Functions
window.getCart = function() {
  return JSON.parse(localStorage.getItem("fruitiva_cart")) || [];
};

window.saveCart = function(cart) {
  localStorage.setItem("fruitiva_cart", JSON.stringify(cart));
  window.updateCartBadges();
};

window.addToCart = function(productId, qty = 1) {
  const product = window.products.find(p => p.id === productId);
  if (!product) return;

  let cart = window.getCart();
  const existing = cart.find(item => item.id === productId);
  if (existing) {
    existing.qty += qty;
  } else {
    cart.push({
      id: product.id,
      name: product.name,
      price: product.price,
      img: product.img,
      qty: qty
    });
  }
  window.saveCart(cart);
  window.showMiniAlert(`${product.name} added to cart! 🛒`);
};

window.updateCartBadges = function() {
  const cart = window.getCart();
  const totalCost = cart.reduce((sum, item) => sum + (item.price * item.qty), 0);
  
  // Update elements that display cart cost
  const cartAmountElements = document.querySelectorAll(".cart-box span, #cart-amount");
  cartAmountElements.forEach(el => {
    el.innerText = `${totalCost.toLocaleString()} RWF`;
  });
};

// Custom toast alert
window.showMiniAlert = function(msg) {
  let alertBox = document.getElementById("cart-mini-alert");
  if (!alertBox) {
    alertBox = document.createElement("div");
    alertBox.id = "cart-mini-alert";
    alertBox.style.cssText = `
      position: fixed;
      bottom: 24px;
      right: 24px;
      background: #16a34a;
      color: white;
      padding: 14px 24px;
      border-radius: 12px;
      box-shadow: 0 10px 25px rgba(22, 163, 74, 0.3);
      font-weight: bold;
      z-index: 10000;
      opacity: 0;
      transform: translateY(20px);
      transition: all 0.3s ease;
      font-family: sans-serif;
    `;
    document.body.appendChild(alertBox);
  }
  alertBox.innerText = msg;
  alertBox.style.opacity = "1";
  alertBox.style.transform = "translateY(0)";
  
  setTimeout(() => {
    alertBox.style.opacity = "0";
    alertBox.style.transform = "translateY(20px)";
  }, 2500);
};

// Initialize badges on page load
document.addEventListener("DOMContentLoaded", () => {
  window.updateCartBadges();
});
